/** All domain experts, flattened, each tagged with the pack it belongs to. */
export const DOMAIN_EXPERTS = DOMAIN_PACKS.flatMap((pack) =>
  pack.experts.map((expert) => ({ ...expert, domain: pack.id })),
)

/** All domain teams, each tagged with the pack it belongs to. */
export const DOMAIN_TEAMS = DOMAIN_PACKS.map((pack) => ({ ...pack.team, domain: pack.id }))

/** Fast pack lookup; built once per process. */
export const DOMAIN_BY_ID = new Map(DOMAIN_PACKS.map((pack) => [pack.id, pack]))

export function getDomain(id) {
  return DOMAIN_BY_ID.get(id) ?? null
}

/** Resolve the pack a review team belongs to (null for core teams). */
export function domainForTeam(teamId) {
  return DOMAIN_PACKS.find((pack) => pack.team.id === teamId) ?? null
}
