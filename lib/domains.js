/**
 * Professional domain packs.
 *
 * The core roster in `lib/experts.js` is deliberately generic: a lens that works
 * for any decision. Real reviews are not generic — a finance panel and a
 * clinical panel disagree about what counts as evidence, what is a red line,
 * and what artifact the decision must leave behind.
 *
 * A domain pack bundles one professional field: five lenses, an evidence ladder
 * (strongest to weakest), the mandatory evidence items, the red flags that
 * degrade a finding, the deliverable artifacts, and one review team. Packs are
 * data, so the panel, the tool and the command can load a field without knowing
 * anything about finance or healthcare.
 *
 * Invariants (checked in test/domains.test.mjs):
 *   - six packs in a fixed order, exactly five experts and one team each
 *   - expert ids are globally unique and prefixed by their field; team ids never
 *     collide with the core `TEAMS` in `lib/teams.js`
 *   - one lead per team, all five experts on the roster, team budget equals the
 *     pack budget, and budgets strictly increase lean < standard < deep
 *   - evidence levels run strongest (A) to weakest; required items, red flags
 *     and artifacts are non-empty so a review can never be "graded" by vibes
 */

